package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

func (g *gen) example(s obj, depth int) any {
	if depth > 32 {
		fatalf("cannot construct finite schema test value")
	}
	if r := str(s, "$ref"); r != "" {
		return g.example(sub(g.schemas, refName(r)), depth+1)
	}
	for _, key := range []string{"oneOf", "anyOf", "allOf"} {
		for _, v := range asSlice(s[key]) {
			if schemaType(v.(obj)) != "null" {
				return g.example(v.(obj), depth+1)
			}
		}
	}
	if values := asSlice(s["enum"]); len(values) > 0 {
		return values[0]
	}
	switch schemaType(s) {
	case "object":
		out := obj{}
		for _, name := range sortedKeys(sub(s, "properties")) {
			out[name] = g.example(sub(sub(s, "properties"), name), depth+1)
		}
		if ap := sub(s, "additionalProperties"); s["properties"] == nil && ap != nil {
			out["example"] = g.example(ap, depth+1)
		}
		return out
	case "array":
		count := 0
		if v, ok := s["minItems"]; ok {
			parsed, err := strconv.Atoi(fmt.Sprint(v))
			if err != nil || parsed < 0 {
				fatalf("invalid minItems constraint %v", v)
			}
			count = parsed
		}
		out := make([]any, count)
		for i := range out {
			out[i] = g.example(sub(s, "items"), depth+1)
		}
		return out
	case "boolean":
		return false
	case "integer", "number":
		if n, ok := s["minimum"]; ok {
			return n
		}
		return json.Number("0")
	case "string":
		if str(s, "format") == "uuid" {
			return "00000000-0000-4000-8000-000000000001"
		}
		value := "example"
		if minimum, ok := s["minLength"]; ok {
			count, err := strconv.Atoi(fmt.Sprint(minimum))
			if err != nil || count < 0 {
				fatalf("invalid minLength constraint %v", minimum)
			}
			if len(value) < count {
				value += strings.Repeat("a", count-len(value))
			}
		}
		return value
	default:
		return obj{"integer": json.Number("9007199254740993"), "null": nil, "unicode": "授权🔐"}
	}
}
func (g *gen) serializationTests() string {
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/gen from sdks/contracts/openapi.json; DO NOT EDIT.
package authgebra
import("bytes";"encoding/json";"reflect";"testing")
func TestEveryNamedModelPreservesJSONShape(t *testing.T) {
 cases:=[]struct{name string;makeModel func()any;input string}{
`)
	for _, name := range sortedKeys(g.schemas) {
		if handTypes[name] {
			continue
		}
		raw, err := json.Marshal(g.example(sub(g.schemas, name), 0))
		if err != nil {
			fatalf("model example: %v", err)
		}
		fmt.Fprintf(&b, "{%q,func()any{return new(%s)},%q},\n", name, pascal(name), raw)
	}
	b.WriteString(`}
 decode:=func(raw []byte)any{ t.Helper();var out any;d:=json.NewDecoder(bytes.NewReader(raw));d.UseNumber();if err:=d.Decode(&out);err!=nil{t.Fatal(err)};return out }
 for _,c:=range cases { t.Run(c.name,func(t *testing.T){
  model:=c.makeModel();if err:=json.Unmarshal([]byte(c.input),model);err!=nil{t.Fatal(err)}
  raw,err:=json.Marshal(model);if err!=nil{t.Fatal(err)}
  if !reflect.DeepEqual(decode([]byte(c.input)),decode(raw)){t.Fatalf("model changed JSON shape: input %s, output %s",c.input,raw)}
 }) }
}
`)
	return strings.TrimSpace(b.String()) + "\n"
}
