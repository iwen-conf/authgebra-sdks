#!/usr/bin/env python3
"""Generate the admin API surface from the reviewed OpenAPI export.

    python tools/generate.py           # rewrite src/authgebra/_generated/*
    python tools/generate.py --check   # fail if the committed output is stale

Input is ``../contracts/openapi.json`` (the single source of truth shared by all SDKs); nothing
is fetched from a server.  Output is deterministic.
"""

from __future__ import annotations

import hashlib
import json
import keyword
import re
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT.parent / "contracts" / "openapi.json"
OUT = ROOT / "src" / "authgebra" / "_generated"
HEADER = '"""GENERATED by tools/generate.py from sdks/contracts/openapi.json - do not edit."""\n\n'
SCHEMA_ANNOTATIONS = frozenset({"description", "title", "default", "example", "examples", "deprecated", "readOnly", "writeOnly", "$comment", "externalDocs", "xml"})
SUPPORTED_SCHEMA_KEYS = SCHEMA_ANNOTATIONS | frozenset({
    "$ref", "type", "properties", "required", "additionalProperties", "propertyNames", "items",
    "oneOf", "anyOf", "allOf", "enum", "format", "minimum", "maximum", "minLength", "maxLength",
    "pattern", "minItems", "maxItems", "uniqueItems",
})


def snake(name: str) -> str:
    out = name.replace("-", "_").replace(".", "_")
    return out + "_" if keyword.iskeyword(out) else out


#: Keyword names owned by the SDK; a query filter with the same name gets a ``query_`` prefix
#: (for example the audit filter ``request_id`` becomes ``query_request_id``).
RESERVED_KWARGS = {"self", "body", "if_match", "idempotency_key", "request_id", "traceparent"}


def query_name(name: str) -> str:
    py = snake(name)
    return f"query_{py}" if py in RESERVED_KWARGS else py


def pascal(tag: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", tag))


def pointer_key(value: str) -> str:
    return value.replace("~", "~0").replace("/", "~1")


class Models:
    """Resolve every known schema shape before rendering language-specific annotations."""

    def __init__(self, spec: dict[str, Any]) -> None:
        self.schemas: dict[str, dict[str, Any]] = {}
        self.names: dict[str, str] = {}
        self.definitions: dict[str, tuple[str, dict[str, Any]]] = {}
        self.component_shapes: dict[str, str] = {}
        request_schemas: list[dict[str, Any]] = []
        response_schemas: list[dict[str, Any]] = []
        for name, schema in sorted(spec["components"]["schemas"].items()):
            pointer = "#/components/schemas/" + pointer_key(name)
            self.names[pointer] = name
            self.definitions[name] = (pointer, schema)
            if "properties" in schema:
                self.component_shapes[self.shape(schema)] = name
        for name, (pointer, schema) in list(self.definitions.items()):
            self.collect(pointer, schema, name)
        for path, item in sorted(spec["paths"].items()):
            for method, operation in sorted(item.items()):
                body_schema = operation.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
                if body_schema is not None:
                    request_schemas.append(body_schema)
                for status, response in sorted(operation.get("responses", {}).items()):
                    schema = response.get("content", {}).get("application/json", {}).get("schema")
                    if schema is not None:
                        response_schemas.append(schema)
                        pointer = f"#/paths/{pointer_key(path)}/{method}/responses/{status}/content/application~1json/schema"
                        self.collect(pointer, schema, pascal(operation["operationId"]) + "Body")
        for pointer, schema in self.schemas.items():
            ref = schema.get("$ref")
            if ref is not None and ref not in self.schemas:
                raise ValueError(f"unresolved $ref at {pointer}: {ref}")
        self.request_models = self.reached_models(request_schemas) - self.reached_models(response_schemas)

    def reached_models(self, roots: list[dict[str, Any]]) -> set[str]:
        reached: set[str] = set()

        def visit(schema: dict[str, Any]) -> None:
            if "$ref" in schema:
                pointer = schema["$ref"]
                if pointer not in reached:
                    reached.add(pointer)
                    visit(self.schemas[pointer])
                return
            if "properties" in schema:
                name = self.component_shapes.get(self.shape(schema))
                if name is not None:
                    reached.add("#/components/schemas/" + pointer_key(name))
                for child in schema["properties"].values():
                    visit(child)
            for keyword_ in ("items", "additionalProperties"):
                if isinstance(schema.get(keyword_), dict):
                    visit(schema[keyword_])
            for keyword_ in ("oneOf", "anyOf", "allOf"):
                for child in schema.get(keyword_, []):
                    visit(child)

        for schema in roots:
            visit(schema)
        return reached

    def collect(self, pointer: str, schema: dict[str, Any], hint: str) -> None:
        if not isinstance(schema, dict):
            raise ValueError(f"unsupported non-object schema at {pointer}")
        unsupported = [key for key in schema if key not in SUPPORTED_SCHEMA_KEYS and not key.startswith("x-")]
        if unsupported:
            raise ValueError(f"unsupported schema assertions at {pointer}: {unsupported}")
        if "$ref" in schema and any(key not in SCHEMA_ANNOTATIONS and not key.startswith("x-") and key != "$ref" for key in schema):
            raise ValueError(f"unsupported assertions beside $ref at {pointer}")
        if not any(key in schema for key in ("type", "$ref", "oneOf", "anyOf", "allOf")) and any(key not in SCHEMA_ANNOTATIONS and not key.startswith("x-") for key in schema):
            raise ValueError(f"unsupported assertions without a structural type at {pointer}")
        if "enum" in schema and (schema.get("type") != "string" or not schema["enum"] or not all(isinstance(value, str) for value in schema["enum"])):
            raise ValueError(f"unsupported non-string enum at {pointer}")
        if "propertyNames" in schema:
            names = schema["propertyNames"]
            if not isinstance(names, dict) or names.get("type") != "string" or any(key != "type" and key not in SCHEMA_ANNOTATIONS for key in names):
                raise ValueError(f"unsupported propertyNames assertions at {pointer}")
        if schema.get("type") == "object" and "properties" not in schema and (schema.get("additionalProperties") is False or "required" in schema):
            raise ValueError(f"unsupported closed or required open-object schema at {pointer}")
        self.schemas[pointer] = schema
        kind = schema.get("type")
        if isinstance(kind, list) and len([t for t in kind if t != "null"]) != 1:
            raise ValueError(f"unsupported type union at {pointer}")
        if schema.get("allOf") and len(schema["allOf"]) != 1:
            raise ValueError(f"unsupported allOf at {pointer}")
        if pointer not in self.names and ("properties" in schema or "enum" in schema or any(k in schema for k in ("oneOf", "anyOf"))):
            existing = self.component_shapes.get(self.shape(schema)) if "properties" in schema else None
            name = existing or hint
            index = 2
            while existing is None and name in self.definitions:
                name, index = hint + str(index), index + 1
            self.names[pointer] = name
            if existing is None:
                self.definitions[name] = (pointer, schema)
        for field, child in sorted(schema.get("properties", {}).items()):
            self.collect(pointer + "/properties/" + pointer_key(field), child, hint + pascal(field))
        for keyword_ in ("items", "additionalProperties"):
            child = schema.get(keyword_)
            if isinstance(child, dict):
                self.collect(pointer + "/" + keyword_, child, hint + ("Item" if keyword_ == "items" else "Value"))
        for keyword_ in ("oneOf", "anyOf", "allOf"):
            for index, child in enumerate(schema.get(keyword_, [])):
                discriminator = next((v["enum"][0] for v in child.get("properties", {}).values() if len(v.get("enum", [])) == 1), None)
                suffix = pascal(str(discriminator)) if discriminator is not None else "Variant" + str(index + 1)
                self.collect(f"{pointer}/{keyword_}/{index}", child, hint + suffix)

    @staticmethod
    def shape(value: Any) -> str:
        def clean(item: Any) -> Any:
            if isinstance(item, dict):
                return {key: clean(child) for key, child in item.items() if key not in ("description", "title", "example", "examples")}
            if isinstance(item, list):
                return [clean(child) for child in item]
            return item
        return json.dumps(clean(value), sort_keys=True)

    def type_of(self, pointer: str, *, defining: bool = False) -> str:
        schema = self.schemas[pointer]
        if "$ref" in schema:
            return self.names[schema["$ref"]]
        if not defining and pointer in self.names:
            return self.names[pointer]
        for key in ("oneOf", "anyOf", "allOf"):
            if key in schema:
                arms = [self.type_of(f"{pointer}/{key}/{index}") for index in range(len(schema[key]))]
                return "Union[" + ", ".join(repr(arm) for arm in arms) + "]" if len(arms) > 1 else arms[0]
        kind = schema.get("type")
        nullable = isinstance(kind, list) and "null" in kind
        if isinstance(kind, list):
            kind = next(k for k in kind if k != "null")
        if kind in ("string", "integer", "number", "boolean", "null"):
            typ = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}[kind]
        elif kind == "array":
            if "items" not in schema:
                raise ValueError(f"array missing items at {pointer}")
            typ = f"list[{self.type_of(pointer + '/items')}]"
        elif kind == "object" and "properties" not in schema:
            additional = schema.get("additionalProperties")
            typ = f"dict[str, {self.type_of(pointer + '/additionalProperties')}]" if isinstance(additional, dict) else "dict[str, JSONValue]"
        elif kind is None and not schema.get("properties"):
            if any(key not in SCHEMA_ANNOTATIONS and not key.startswith("x-") for key in schema):
                raise ValueError(f"unsupported schema at {pointer}: {sorted(schema)}")
            typ = "JSONValue"
        elif "properties" in schema:
            typ = self.names[pointer]
        else:
            raise ValueError(f"unsupported type at {pointer}: {kind}")
        return typ + " | None" if nullable else typ

    def render(self, ops: list[dict[str, Any]]) -> str:
        out = [HEADER, "from __future__ import annotations\n\n", "from dataclasses import dataclass\nfrom enum import Enum\nfrom typing import ClassVar, TypeAlias, Union\n\n", "from .._model import JSONValue, Model, StringEnum, UNSET, Unset\nfrom ..models import ApiResult\n\n"]
        aliases: list[str] = []
        model_rows: list[str] = []
        enum_rows: list[str] = []
        for name, (pointer, schema) in sorted(self.definitions.items()):
            out.append(f"# Source: {pointer}\n")
            if "enum" in schema:
                out.append(f"class {name}(StringEnum):\n")
                used: set[str] = set()
                for index, value in enumerate(schema["enum"]):
                    constant = re.sub(r"[^A-Za-z0-9_]", "_", str(value)).upper()
                    if not constant or constant[0].isdigit() or constant in used:
                        constant = "VALUE_" + str(index)
                    used.add(constant)
                    out.append(f"    {constant} = {value!r}\n")
                enum_rows.append(f"    {pointer!r}: {name},\n")
                out.append("\n")
            elif "properties" in schema:
                out.append(f"@dataclass(frozen=True, kw_only=True, eq=False, repr=False)\nclass {name}(Model):\n")
                out.append(f"    __schema_pointer__: ClassVar[str] = {pointer!r}\n")
                out.append(f"    __request_model__: ClassVar[bool] = {pointer in self.request_models!r}\n")
                mapping = {field: snake(field) for field in schema["properties"]}
                if len(set(mapping.values())) != len(mapping):
                    raise ValueError(f"Python field name collision at {pointer}")
                out.append(f"    __json_fields__: ClassVar[dict[str, str]] = {mapping!r}\n")
                required = set(schema.get("required", []))
                for field in sorted(schema["properties"]):
                    child = pointer + "/properties/" + pointer_key(field)
                    annotation = self.type_of(child)
                    suffix = "" if field in required else " | Unset = UNSET"
                    out.append(f"    # Source: {child}\n    {snake(field)}: {annotation}{suffix}\n")
                out.append("\n")
            else:
                aliases.append(f"# Source: {pointer}\n{name}: TypeAlias = {self.type_of(pointer, defining=True)}\n")
        out.extend(aliases)
        for pointer, name in sorted(self.names.items()):
            if "properties" in self.schemas[pointer]:
                model_rows.append(f"    {pointer!r}: {name},\n")
        out.append("\n")
        for op in ops:
            name = op["response_type"]
            out.append(f"@dataclass(frozen=True)\nclass {name}(ApiResult):\n    \"\"\"{op['method']} {op['path']}; body schema {op['response_pointer']}.\"\"\"\n    data: {self.type_of(op['response_pointer'])}\n\n")
        out.append("MODEL_TYPES: dict[str, type[Model]] = {\n" + "".join(model_rows) + "}\n")
        out.append("ENUM_TYPES: dict[str, type[Enum]] = {\n" + "".join(enum_rows) + "}\n")
        # Descriptors are parser metadata, not a replacement for the generated public fields.
        descriptors: dict[str, dict[str, Any]] = {}
        for pointer, schema in self.schemas.items():
            row = {key: value for key, value in schema.items() if key not in ("description", "title", "example", "examples", "properties", "items", "additionalProperties", "oneOf", "anyOf", "allOf")}
            if "properties" in schema:
                row["properties"] = {field: {} for field in schema["properties"]}
            if "additionalProperties" in schema:
                row["additionalProperties"] = {} if isinstance(schema["additionalProperties"], dict) else schema["additionalProperties"]
            for key in ("oneOf", "anyOf", "allOf"):
                if key in schema:
                    row[key] = [{} for _ in schema[key]]
            descriptors[pointer] = row
        out.append("SCHEMAS: dict[str, dict[str, object]] = " + repr(descriptors) + "\n")
        return "".join(out)


def py_type(schema: dict[str, Any]) -> str:
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), "string")
    return {"integer": "int", "boolean": "bool"}.get(str(kind), "str")


def operations(spec: dict[str, Any]) -> list[dict[str, Any]]:
    ops: list[dict[str, Any]] = []
    for path, item in spec["paths"].items():
        for method, op in item.items():
            params = op.get("parameters", [])
            body = op.get("requestBody")
            responses = op.get("responses", {})
            status = next((s for s in sorted(responses) if s.startswith("2")), None)
            if status is None:
                raise ValueError(f"operation has no success response: {op['operationId']}")
            response_schema = responses[status].get("content", {}).get("application/json", {}).get("schema")
            if response_schema is None:
                raise ValueError(f"unsupported no-content response: {op['operationId']}")
            response_pointer = f"#/paths/{pointer_key(path)}/{method}/responses/{status}/content/application~1json/schema"
            if "$ref" in response_schema:
                response_pointer = response_schema["$ref"]
                response_schema = spec["components"]["schemas"][response_pointer.split("/")[-1]]
            bare = "data" not in response_schema.get("properties", {})
            if not bare:
                response_pointer += "/properties/data"
            response_type = pascal(op["operationId"]) + "Response"
            if response_type in spec["components"]["schemas"]:
                response_type = pascal(op["operationId"]) + "OperationResponse"
            ops.append(
                {
                    "id": op["operationId"],
                    "tag": op["tags"][0],
                    "method": method.upper(),
                    "path": path,
                    "summary": (op.get("summary") or op.get("description") or op["operationId"].replace("_", " ")).strip().split("\n")[0],
                    "path_params": [p["name"] for p in params if p["in"] == "path"],
                    "query": [p for p in params if p["in"] == "query"],
                    "if_match": next((p for p in params if p["in"] == "header" and p["name"] == "If-Match"), None),
                    "idem": any(p["in"] == "header" and p["name"] == "Idempotency-Key" for p in params),
                    "body": None if body is None else bool(body.get("required", False)),
                    "body_type": None if body is None else body["content"]["application/json"]["schema"]["$ref"].split("/")[-1],
                    "response_type": response_type,
                    "response_pointer": response_pointer,
                    "bare": bare,
                }
            )
    ops.sort(key=lambda o: (o["tag"], o["id"]))
    ids = [o["id"] for o in ops]
    assert len(ids) == len(set(ids)), "operationId must be unique"
    return ops


def render_method(op: dict[str, Any], aio: bool) -> str:
    pos = [f"{snake(n)}: str" for n in op["path_params"]]
    required_kw: list[str] = []
    optional_kw: list[str] = []
    if op["if_match"] is not None:
        (required_kw if op["if_match"].get("required") else optional_kw).append(
            "if_match: str" if op["if_match"].get("required") else "if_match: str | None = None"
        )
    if op["body"] is True:
        required_kw.append(f"body: models.{op['body_type']} | Mapping[str, object]")
    elif op["body"] is False:
        optional_kw.append(f"body: models.{op['body_type']} | Mapping[str, object] | None = None")
    query_items: list[str] = []
    for param in op["query"]:
        name = query_name(param["name"])
        typ = py_type(param.get("schema", {}))
        if param.get("required"):
            required_kw.append(f"{name}: {typ}")
        else:
            optional_kw.append(f"{name}: {typ} | None = None")
        query_items.append(f'"{param["name"]}": {name}')
    if op["idem"]:
        optional_kw.append("idempotency_key: str | None = None")
    optional_kw += ["request_id: str | None = None", "traceparent: str | None = None"]
    sig = ", ".join(["self"] + pos + ["*"] + required_kw + optional_kw)
    template = op["path"]
    path_expr = (
        f'_path("{template}", ' + ", ".join(f"{n}={snake(n)}" for n in op["path_params"]) + ")"
        if op["path_params"]
        else f'"{template}"'
    )
    kind, await_ = ("async def", "await ") if aio else ("def", "")
    lines = [
        f"    {kind} {snake(op['id'])}({sig}) -> models.{op['response_type']}:",
        f'        """{op["summary"].replace(chr(34), chr(39))}\n\n        ``{op["method"]} {template}``\n        """',
        f"        _sdk_result = {await_}self._c.request(",
        f'            "{op["method"]}",',
        f"            {path_expr},",
    ]
    if query_items:
        lines.append("            query={" + ", ".join(query_items) + "},")
    if op["body"] is not None:
        lines.append("            json=request_body(body),")
    if op["if_match"] is not None:
        lines.append("            if_match=if_match,")
    if op["idem"]:
        lines.append("            idempotency_key=idempotency_key,")
    lines += ["            request_id=request_id,", "            traceparent=traceparent,"]
    if op["bare"]:
        lines.append("            envelope=False,")
    lines.append("        )")
    lines.append(f"        return typed_result(_sdk_result, models.{op['response_type']}, {op['response_pointer']!r})")
    return "\n".join(lines)


def render_module(ops: list[dict[str, Any]], aio: bool) -> str:
    requester = "AsyncRequester" if aio else "SyncRequester"
    out = [
        HEADER,
        "from __future__ import annotations\n\n",
        "from collections.abc import Mapping\n\n",
        f"from .._core import {requester}\n",
        "from .._core import path_with as _path\n",
        "from .._model import request_body, typed_result\nfrom . import models\n\n",
    ]
    tags = sorted({o["tag"] for o in ops})
    for tag in tags:
        cls = pascal(tag) + "Api"
        out.append(f"\nclass {cls}:\n")
        out.append(f"    def __init__(self, client: {requester}) -> None:\n        self._c = client\n\n")
        out.append("\n\n".join(render_method(o, aio) for o in ops if o["tag"] == tag))
        out.append("\n\n")
    admin = "AsyncAdminClient" if aio else "AdminClient"
    out.append(f"\nclass {admin}:\n")
    out.append('    """Every ``/api/v1`` operation grouped by OpenAPI tag (``admin.users.list_users`` ...)."""\n\n')
    out.append(f"    def __init__(self, client: {requester}) -> None:\n")
    for tag in tags:
        out.append(f"        self.{snake(tag)} = {pascal(tag)}Api(client)\n")
    return "".join(out).rstrip() + "\n"


def render_operations(ops: list[dict[str, Any]], digest: str) -> str:
    rows = "".join(
        f'    ("{o["id"]}", "{snake(o["tag"])}", "{o["method"]}", "{o["path"]}"),\n' for o in ops
    )
    return (
        HEADER
        + f'SPEC_SHA256 = "{digest}"\n\n'
        + "#: (operationId, admin group attribute, HTTP method, path template)\n"
        + "OPERATIONS: tuple[tuple[str, str, str, str], ...] = (\n"
        + rows
        + ")\n"
    )


def render_codes(spec: dict[str, Any]) -> str:
    codes = spec["components"]["schemas"]["ApiErrorCode"]["enum"]
    body = "".join(f'        "{c}",\n' for c in codes)
    return HEADER + "KNOWN_ERROR_CODES: frozenset[str] = frozenset(\n    {\n" + body + "    }\n)\n"


def build() -> dict[str, str]:
    raw = SPEC.read_bytes()
    spec = json.loads(raw)
    ops = operations(spec)
    digest = hashlib.sha256(raw).hexdigest()
    models = Models(spec)
    return {
        "__init__.py": HEADER,
        "codes.py": render_codes(spec),
        "models.py": models.render(ops),
        "provenance.json": json.dumps({
            "schemas": [{"pointer": pointer, "type": models.type_of(pointer),
                         "file": "sdks/python/src/authgebra/_generated/models.py",
                         "fields": [{"pointer": pointer + "/properties/" + pointer_key(field),
                                     "name": snake(field)} for field in sorted(schema.get("properties", {}))]}
                        for pointer, schema in sorted(models.schemas.items())],
            "operations": [{"operationId": op["id"], "request": op["body_type"],
                            "response": op["response_type"], "responseDataPointer": op["response_pointer"]} for op in ops],
            "dynamicExceptions": [{"pointer": pointer, "type": "JSONValue",
                                   "reason": "The reviewed schema permits any JSON value, including scalars, arrays and null.",
                                   "test": "tests/test_typed_models.py::test_each_open_json_exception_preserves_json_values"}
                                  for pointer in sorted(models.schemas) if models.type_of(pointer) == "JSONValue"],
        }, sort_keys=True, indent=2) + "\n",
        "operations.py": render_operations(ops, digest),
        "sync.py": render_module(ops, aio=False),
        "aio.py": render_module(ops, aio=True),
    }


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        with tempfile.TemporaryDirectory(prefix="authgebra-python-generated-") as directory:
            generated = Path(directory)
            for name, text in files.items():
                (generated / name).write_bytes(text.encode("utf-8"))
            stale = [name for name in files if not (OUT / name).is_file() or (OUT / name).read_bytes() != (generated / name).read_bytes()]
        if stale:
            print(f"stale generated files: {stale}; run tools/generate.py", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_bytes(text.encode("utf-8"))
    print(f"generated {len(files)} files for {sum(1 for _ in operations(json.loads(SPEC.read_bytes())))} operations")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
