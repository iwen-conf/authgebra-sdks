#!/usr/bin/env python3
"""Generate src/admin_ops.zig from sdks/contracts/openapi.json (one typed method per operationId).

Usage: python3 tools/gen_admin.py            # rewrite src/admin_ops.zig
       python3 tools/gen_admin.py --check    # fail if the committed file is stale

Typed: path parameters, query parameters, If-Match / Idempotency-Key headers.
Bodies: named models, optional/null states and tagged unions. RawAdminClient is an explicit compatibility escape hatch.
"""
import json, re, sys, pathlib, tempfile
from model_gen import Models, pascal

root = pathlib.Path(__file__).resolve().parents[1]
spec_path = root.parent / "contracts" / "openapi.json"
out_path = root / "src" / "admin_ops.zig"
spec = json.loads(spec_path.read_text())
models = Models(spec)

ZIG_KEYWORDS = {"from", "to", "type", "error", "test", "fn", "var", "const", "if", "else", "for",
                "while", "return", "try", "catch", "and", "or", "async", "await", "defer", "enum",
                "struct", "union", "switch", "break", "continue", "pub", "usingnamespace"}

def camel(op_id):
    parts = op_id.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])

def field_name(n):
    n = re.sub(r"[^A-Za-z0-9_]", "_", n).lower()
    return f'@"{n}"' if n in ZIG_KEYWORDS else n

ops = []
for path, item in spec["paths"].items():
    for method, op in item.items():
        ops.append((op["operationId"], method.upper(), path, op))
ops.sort(key=lambda o: o[0])

lines = []
w = lines.append
w("// GENERATED by tools/gen_admin.py from sdks/contracts/openapi.json — DO NOT EDIT.")
w("// Regenerate with `python3 tools/gen_admin.py`; CI runs `--check`.")
w("const std = @import(\"std\");")
w("const client_mod = @import(\"client.zig\");")
w("const errors = @import(\"errors.zig\");")
w("const models = @import(\"models.zig\");")
w("")
w("pub const Json = std.json.Value;")
w("pub const Outcome = errors.Outcome(Json);")
w("")
w("pub const Operation = struct {")
w("    id: []const u8,")
w("    method: []const u8,")
w("    path: []const u8,")
w("};")
w("")
w("/// Every operation in the reviewed OpenAPI export (used by the coverage test).")
w("pub const operations = [_]Operation{")
for op_id, method, path, _ in ops:
    w(f'    .{{ .id = "{op_id}", .method = "{method}", .path = "{path}" }},')
w("};")
w("")
def emit_client(raw):
    client_name = "RawAdminClient" if raw else "AdminClient"
    w("/// Admin surface: one method per operationId, each a thin wrapper over `Client.send`.")
    w("/// Named contract models; RawAdminClient retains explicit dynamic access.")
    w("pub const " + client_name + " = struct {")
    w("    client: *client_mod.Client,")
    w("")
    w("    const Self = " + client_name + ";")
    w("")
    w("    pub fn init(client: *client_mod.Client) " + client_name + " {")
    w("        return .{ .client = client };")
    w("    }")
    w("")
    for op_id, method, path, op in ops:
        params = op.get("parameters", [])
        path_params = [p for p in params if p["in"] == "path"]
        query_params = [p for p in params if p["in"] == "query"]
        header_names = {p["name"]: p for p in params if p["in"] == "header"}
        has_body = "requestBody" in op
        body_required = has_body and op["requestBody"].get("required", False)
        body_type = "Json"
        response_type, envelope = models.response_type(op)
        response_type = "models." + response_type if not response_type.startswith("[]const ") else "[]const models." + response_type.removeprefix("[]const ")
        if raw:
            response_type, envelope = "Json", True
        if has_body and not raw:
            body_schema = op["requestBody"]["content"]["application/json"]["schema"]
            body_type = "models." + models.ty(body_schema, camel(op_id) + "Body", "#/paths")
        fields = []
        for p in path_params:
            fields.append(f"            {field_name(p['name'])}: []const u8,")
        for p in query_params:
            qt = "[]const u8" if raw else models.ty(p["schema"], camel(op_id) + pascal(p["name"]), "#/paths/" + path.replace("/", "~1") + "/" + method.lower() + "/parameters/" + str(params.index(p)) + "/schema")
            if qt not in ("[]const u8", "bool", "i32", "i64", "u32", "u64", "u8", "u16", "f64"):
                qt = "models." + qt
            fields.append(f"            {field_name(p['name'])}: ?{qt} = null,")
        if "If-Match" in header_names:
            if header_names["If-Match"].get("required"):
                fields.append("            if_match: []const u8,")
            else:
                fields.append("            if_match: ?[]const u8 = null,")
        if "Idempotency-Key" in header_names:
            fields.append("            idempotency_key: ?[]const u8 = null,")
        if has_body:
            fields.append(f"            body: {body_type}," if body_required else f"            body: ?{body_type} = null,")
        fn = camel(op_id)
        w(f"        /// `{method} {path}`")
        w(f"        pub fn {fn}(self: Self, args: struct {{")
        for f in fields:
            w(f)
        w("            options: client_mod.CallOptions = .{},")
        w("        }) !errors.Outcome(" + response_type + ") {")
        # path building
        tmpl = path
        fmt_args = []
        for p in path_params:
            tmpl = tmpl.replace("{" + p["name"] + "}", "{s}")
            fmt_args.append("enc_" + field_name(p["name"]).strip('@"'))
        if path_params or has_body:
            w("            const gpa = self.client.gpa;")
        for p in path_params:
            n = field_name(p["name"])
            v = n.strip('@"')
            w(f"            var enc_{v}: std.ArrayList(u8) = .empty;")
            w(f"            defer enc_{v}.deinit(gpa);")
            w(f"            try client_mod.percentEncode(gpa, &enc_{v}, args.{n});")
        if path_params:
            w(f'            const path = try std.fmt.allocPrint(gpa, "{tmpl}", .{{ {", ".join(a + ".items" for a in fmt_args)} }});')
            w("            defer gpa.free(path);")
        else:
            w(f'            const path: []const u8 = "{path}";')
        if query_params:
            w(f"            var query: [{len(query_params)}]client_mod.QueryParam = undefined;")
            w("            var query_len: usize = 0;")
            for p in query_params:
                n = field_name(p["name"])
                expression = "v"
                if not raw:
                    ps = models.normalized(p["schema"])
                    if ps.get("type") in ("integer", "number"):
                        w("            var query_" + n + "_buf: [64]u8 = undefined;")
                        expression = 'try std.fmt.bufPrint(&query_' + n + '_buf, "{d}", .{v})'
                    elif ps.get("type") == "boolean":
                        expression = 'if (v) "true" else "false"'
                    elif 'enum' in ps or '$ref' in ps:
                        expression = '@tagName(v)'
                w(f"            if (args.{n}) |v| {{ query[query_len] = .{{ .name = \"{p['name']}\", .value = {expression} }}; query_len += 1; }}")
        if has_body:
            if not raw:
                if body_required:
                    w("            try args.body.validate();")
                else:
                    w("            if (args.body) |v| try v.validate();")
            if body_required:
                w("            const body = try std.json.Stringify.valueAlloc(gpa, args.body, .{});")
                w("            defer gpa.free(body);")
            else:
                w("            const body: ?[]u8 = if (args.body) |b| try std.json.Stringify.valueAlloc(gpa, b, .{}) else null;")
                w("            defer if (body) |b| gpa.free(b);")
        w("            return self.client.send(" + response_type + ", .{")
        w(f"                .method = .{method},")
        w("                .path = path,")
        if query_params:
            w("                .query = query[0..query_len],")
        if has_body:
            w("                .body = body,")
        if "If-Match" in header_names:
            w("                .if_match = args.if_match,")
        if "Idempotency-Key" in header_names:
            w("                .idempotency_key = args.idempotency_key,")
        if not envelope:
            w("                .bare_response = true,")
        success = sorted(code for code in op["responses"] if code.startswith("2"))[0]
        success_schema = op["responses"][success]["content"]["application/json"]["schema"]
        if success_schema.get("$ref", "").split("/")[-1].startswith("PagedResponse_"):
            w("                .paged_response = true,")
        if op_id in ("check", "batch_check", "explain", "list_authorized_resources"):
            w("                .read_only = true,")
        w("                .options = args.options,")
        w("            });")
        w("        }")
        w("")
    w("};")

emit_client(False)
emit_client(True)
text = "\n".join(lines) + "\n"
outputs = {"admin_ops.zig": text, "models.zig": models.generate(), "model_roundtrip_test.zig": models.tests()}

# Formatting is part of deterministic generation, never a workspace repair in --check.
import subprocess
for name, source in list(outputs.items()):
    outputs[name] = subprocess.run(["zig", "fmt", "--stdin"], input=source, capture_output=True, text=True, check=True).stdout
outputs["models.provenance.json"] = json.dumps({"aliases": [{"pointer": pointer, "target": "#/components/schemas/" + target, "type": target} for pointer, target in sorted(models.aliases.items())], "models": [{"pointer": pointer, "type": name, "file": "sdks/zig/src/models.zig"} for name, (_, pointer) in sorted(models.entries.items())], "fields": sorted(models.fields, key=lambda f: f["pointer"]), "dynamic_exceptions": sorted(models.exceptions, key=lambda e: e["pointer"])}, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
if "--check" in sys.argv:
    with tempfile.TemporaryDirectory(prefix="authgebra-zig-generated-") as directory:
        candidate = pathlib.Path(directory)
        for name, source in outputs.items():
            (candidate / name).write_bytes(source.encode("utf-8"))
        stale = [name for name in outputs if not (root / "src" / name).exists() or (root / "src" / name).read_bytes() != (candidate / name).read_bytes()]
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        sys.exit(1)
    print(f"Zig generated artifacts up to date ({len(ops)} operations, {len(models.entries)} models)")
else:
    for name, source in outputs.items():
        (root / "src" / name).write_text(source)
    print(f"generated {len(ops)} operations, {len(models.entries)} named models")
